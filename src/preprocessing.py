"""
Preprocessing pipelines and train/test separation for Early and Mid-Term experiments.
"""

from typing import Tuple, List, Dict, Any
import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.model_selection import train_test_split

import sys
from pathlib import Path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.append(str(PROJECT_ROOT))

from config.settings import SEED, TARGET_COL, AT_RISK_THRESHOLD
from src.data_loader import load_raw_data
from src.feature_engineering import add_engineered_features

CATEGORICAL_COLS = [
    "school", "sex", "address", "famsize", "Pstatus", "Mjob", "Fjob",
    "reason", "guardian", "schoolsup", "famsup", "paid", "activities",
    "nursery", "higher", "internet", "romantic"
]

BASE_NUMERIC_COLS = [
    "age", "Medu", "Fedu", "traveltime", "studytime", "failures",
    "famrel", "freetime", "goout", "Dalc", "Walc", "health", "absences",
    "parent_edu_avg", "total_alc", "study_travel_ratio", "academic_support_any"
]

MIDTERM_ADDITIONAL_COLS = ["G1", "G2"]


def get_feature_columns(experiment: str = "A") -> Tuple[List[str], List[str]]:
    """
    Retrieve categorical and numeric feature column lists based on experiment mode.
    Experiment A: Early Prediction (excludes G1 and G2).
    Experiment B: Mid-Term Prediction (includes G1 and G2).
    """
    cat_cols = CATEGORICAL_COLS.copy()
    if experiment.upper() == "A":
        num_cols = BASE_NUMERIC_COLS.copy()
    elif experiment.upper() == "B":
        num_cols = BASE_NUMERIC_COLS.copy() + MIDTERM_ADDITIONAL_COLS.copy()
    else:
        raise ValueError(f"Unknown experiment '{experiment}'. Expected 'A' or 'B'.")
    return cat_cols, num_cols


def build_preprocessor(cat_cols: List[str], num_cols: List[str]) -> ColumnTransformer:
    """Build a ColumnTransformer applying OneHotEncoder to categorical and StandardScaler to numeric features."""
    preprocessor = ColumnTransformer(
        transformers=[
            ("num", StandardScaler(), num_cols),
            ("cat", OneHotEncoder(handle_unknown="ignore", sparse_output=False), cat_cols),
        ],
        remainder="drop"
    )
    return preprocessor


def get_feature_names_from_transformer(preprocessor: ColumnTransformer, cat_cols: List[str], num_cols: List[str]) -> List[str]:
    """Extract human-readable feature names generated by ColumnTransformer."""
    names = list(num_cols)
    cat_encoder = preprocessor.named_transformers_["cat"]
    if hasattr(cat_encoder, "get_feature_names_out"):
        encoded_cat_names = list(cat_encoder.get_feature_names_out(cat_cols))
        names.extend(encoded_cat_names)
    return names


def prepare_data(
    experiment: str = "A",
    target_type: str = "regression",
    test_size: float = 0.2,
    random_state: int = SEED,
    raw_df: pd.DataFrame = None
) -> Dict[str, Any]:
    """
    End-to-end data preparation returning train/test splits, preprocessor, and feature names.
    Prevents data leakage by fitting the preprocessor strictly on the training set.
    """
    if raw_df is None:
        raw_df = load_raw_data()

    df = add_engineered_features(raw_df)
    cat_cols, num_cols = get_feature_columns(experiment)

    all_features = cat_cols + num_cols
    X = df[all_features].copy()

    if target_type == "regression":
        y = df[TARGET_COL].copy()
        stratify_target = None
    elif target_type == "classification":
        y = df["at_risk"].copy()
        stratify_target = y  # Preserves at-risk class balance
    else:
        raise ValueError(f"Unsupported target_type: {target_type}. Expected 'regression' or 'classification'.")

    # Split dataset
    X_train_raw, X_test_raw, y_train, y_test = train_test_split(
        X, y,
        test_size=test_size,
        random_state=random_state,
        stratify=stratify_target
    )

    # Preprocessor fitted strictly on training data
    preprocessor = build_preprocessor(cat_cols, num_cols)
    X_train_arr = preprocessor.fit_transform(X_train_raw)
    X_test_arr = preprocessor.transform(X_test_raw)

    feature_names = get_feature_names_from_transformer(preprocessor, cat_cols, num_cols)

    X_train = pd.DataFrame(X_train_arr, columns=feature_names, index=X_train_raw.index)
    X_test = pd.DataFrame(X_test_arr, columns=feature_names, index=X_test_raw.index)

    return {
        "X_train": X_train,
        "X_test": X_test,
        "X_train_raw": X_train_raw,
        "X_test_raw": X_test_raw,
        "y_train": y_train,
        "y_test": y_test,
        "preprocessor": preprocessor,
        "feature_names": feature_names,
        "cat_cols": cat_cols,
        "num_cols": num_cols,
        "experiment": experiment,
        "target_type": target_type
    }
